zt_err_t zt_ui_font_glyph(uint8_t ascii, uint8_t *out, size_t capacity,
                        uint8_t *width, uint8_t *height, size_t *written)
{
    if (!out || !width || !height || !written) return ZT_ERR_INVALID_ARG;
    *written = 0;
    if (capacity < 5) return ZT_ERR_NO_SPACE;
    if (ascii < ZT_ASCII_PRINTABLE_MIN || ascii > ZT_ASCII_PRINTABLE_MAX)
        return ZT_ERR_INVALID_ARG;
    if (ascii >= 'a' && ascii <= 'z') ascii -= 'a' - 'A';
    memcpy(out, ascii_font[ascii - 32], 5);
    *width = 5;
    *height = 7;
    *written = 5;
    return ZT_OK;
}
